test('activity opens with the requested level and reuses an open dialog',async t=>{
  const controls=new Map(['#activity-level','#activity-account','#activity-close','#activity-copy','#activity-clear','#activity-entries','#activity-count','#activity-feedback'].map(id=>[id,{value:'',innerHTML:'',querySelectorAll:()=>[],querySelector:()=>null,setAttribute(){},removeAttribute(){},focus(){}}]));
  let shows=0;
  const dialog={open:false,innerHTML:'',querySelector:id=>controls.get(id),querySelectorAll:()=>[controls.get('#activity-level'),controls.get('#activity-account')],addEventListener(){},showModal(){assert.equal(this.open,false);this.open=true;shows++;},close(){this.open=false;}};
  const elements=new Map(['#activity-status','#notice','#view-activity'].map(id=>[id,{dataset:{},setAttribute(){}}]));
  elements.set('#activity-dialog',dialog);
  t.mock.method(globalThis,'setInterval',()=>0);
  const oldDocument=globalThis.document;
  globalThis.document={querySelector:id=>elements.get(id),hidden:false};
  t.mock.method(globalThis,'fetch',async()=>({ok:true,json:async()=>({entries:[]})}));
  t.after(()=>{globalThis.document=oldDocument;});
  const activity=createActivity({csrf:()=>''});
  activity.open('error');assert.equal(shows,0);
  activity.configure(true);
  for(const [i,level] of ['error','warning','info'].entries())activity.receive({id:i+1,time:'2026-11-03T00:00:00Z',level,phase:'diagnostic',operation:level,message:level+' fixture',duration_ms:null});
  activity.open('error');
  assert.equal(controls.get('#activity-level').value,'error');
  assert.match(controls.get('#activity-entries').innerHTML,/error fixture/);
  assert.doesNotMatch(controls.get('#activity-entries').innerHTML,/warning fixture|info fixture/);
  activity.open('warning');assert.equal(shows,1);
  assert.match(controls.get('#activity-entries').innerHTML,/warning fixture/);
  assert.doesNotMatch(controls.get('#activity-entries').innerHTML,/error fixture|info fixture/);
  elements.get('#view-activity').onclick();assert.equal(shows,1);
  assert.equal(controls.get('#activity-level').value,'');
  for(const level of ['error','warning','info'])assert.match(controls.get('#activity-entries').innerHTML,new RegExp(level+' fixture'));
  dialog.close();activity.open('warning');assert.equal(shows,2);
  activity.configure(false);activity.open();assert.equal(shows,2);assert.equal(dialog.open,false);
});

test('local errors remain visible for eight seconds and explicit work takes precedence',async t=>{
  const elements=new Map(['#activity-status','#notice','#view-activity','#activity-dialog'].map(id=>[id,{
    dataset:{},setAttribute(name,value){this[name]=value;},addEventListener(){},open:false,
  }]));
  t.mock.method(globalThis,'setInterval',()=>0);
  t.mock.timers.enable({apis:['setTimeout']});
  const oldDocument=globalThis.document,oldFetch=globalThis.fetch;
  globalThis.document={querySelector:id=>elements.get(id),hidden:false};
  const posts=[];
  globalThis.fetch=async(_url,options)=>{if(options.method==='POST')posts.push(JSON.parse(options.body));return {ok:true,json:async()=>({entries:[]})};};
  t.after(()=>{globalThis.document=oldDocument;globalThis.fetch=oldFetch;});
  const activity=createActivity({csrf:()=>''}),status=elements.get('#notice');
  activity.configure(true);
  activity.notice('Unknown command',true,{log:false});
  assert.equal(posts.length,0);
  assert.equal(elements.get('#view-activity').dataset.attention,'');
  t.mock.timers.tick(1200);
  assert.equal(status.textContent,'Unknown command');
  activity.receive({id:1,level:'warning',phase:'complete',message:'Background sync warning'});
  assert.equal(status.textContent,'Unknown command');
  assert.match(elements.get('#view-activity').innerHTML,/1 warning/);
  t.mock.timers.tick(6799);
  assert.equal(status.textContent,'Unknown command');
  assert.equal(status.role,'alert');
  t.mock.timers.tick(1);
  assert.equal(status.textContent,'Ready.');
  activity.notice('Invalid parameter',true);
  assert.deepEqual(posts.at(-1),{action:'notice',message:'Invalid parameter',error:true});
  activity.notice('Saved');
  assert.equal(status.textContent,'Saved');
  t.mock.timers.tick(1200);
  assert.equal(status.textContent,'Ready.');
  activity.notice('Unknown command',true);
  const task=activity.queued('Loading…');
  activity.notice('Another error',true);
  activity.running(task);
  assert.equal(status.textContent,'Loading…');
  assert.equal(status.role,'status');
  activity.done(task);
  t.mock.timers.tick(1200);
  assert.equal(status.textContent,'Ready.');
  activity.notice('Error before logout',true);
  activity.configure(false);
  assert.equal(status.textContent,'Ready.');
  t.mock.timers.tick(8000);
  assert.equal(status.textContent,'Ready.');
});

test('valid commands dismiss only command errors and preserve activity and replacement timers',async t=>{
  const elements=new Map(['#activity-status','#notice','#view-activity','#activity-dialog'].map(id=>[id,{
    dataset:{},setAttribute(name,value){this[name]=value;},addEventListener(){},open:false,
  }]));
  t.mock.method(globalThis,'setInterval',()=>0);
  t.mock.timers.enable({apis:['setTimeout']});
  const oldDocument=globalThis.document;
  globalThis.document={querySelector:id=>elements.get(id),hidden:false};
  t.mock.method(globalThis,'fetch',async()=>({ok:true,json:async()=>({entries:[]})}));
  t.after(()=>{globalThis.document=oldDocument;});
  const activity=createActivity({csrf:()=>''}),status=elements.get('#notice'),bar=elements.get('#activity-status'),button=elements.get('#view-activity');
  activity.configure(true);
  activity.receive({id:1,level:'error',phase:'diagnostic',message:'Provider error'});
  activity.receive({id:2,level:'warning',phase:'diagnostic',message:'Provider warning'});
  const badge=button.innerHTML;
  activity.notice('Unknown command',true,{log:false});
  t.mock.timers.tick(7000);
  activity.clearCommandError();
  assert.equal(status.textContent,'Ready.');assert.equal(status.role,'status');assert.equal(bar.dataset.level,'info');
  assert.equal(button.innerHTML,badge);
  activity.notice('Context error',true,{log:false});
  t.mock.timers.tick(1000);
  assert.equal(status.textContent,'Context error');
  t.mock.timers.tick(6999);
  assert.equal(status.textContent,'Context error');
  t.mock.timers.tick(1);assert.equal(status.textContent,'Ready.');
  activity.notice('Parse error',true,{log:false});
  t.mock.timers.tick(7000);
  activity.notice('Replacement parse error',true,{log:false});
  t.mock.timers.tick(7999);assert.equal(status.textContent,'Replacement parse error');
  t.mock.timers.tick(1);assert.equal(status.textContent,'Ready.');
  activity.notice('Provider failure',true);
  activity.clearCommandError();assert.equal(status.textContent,'Provider failure');assert.equal(status.role,'alert');
  const queued=activity.queued('Waiting…'),running=activity.queued('Loading…');activity.running(running);
  activity.notice('Unknown command',true,{log:false});activity.clearCommandError();
  assert.equal(status.textContent,'Loading… · 1 queued');assert.equal(bar.dataset.level,'busy');
  activity.done(running);
  activity.notice('Unknown command',true,{log:false});activity.clearCommandError();
  assert.equal(status.textContent,'1 operation(s) queued…');
  activity.done(queued);activity.configure(false);
});
